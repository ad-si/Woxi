/// The tabulated precedence of the built-in symbol `name`, if it has one
/// other than the default 670.
pub(crate) fn tabulated_precedence(name: &str) -> Option<f64> {
  PRECEDENCE_TABLE
    .binary_search_by(|(entry, _)| entry.as_bytes().cmp(name.as_bytes()))
    .ok()
    .map(|i| PRECEDENCE_TABLE[i].1)
}
