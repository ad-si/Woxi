//! Every named character the Wolfram Language reads, with the code point it
//! stores for it.
//!
//! The table is Wolfram's own — it is a transcription of
//! `SystemFiles/FrontEnd/TextResources/UnicodeCharacters.tr` from a Wolfram
//! Engine installation, verified name by name against
//! `ToCharacterCode["\\[Name]"]` under `wolframscript`. Keep it that way:
//! regenerate it from a newer `UnicodeCharacters.tr` rather than adding a
//! single name by hand, so a package that writes a character nobody thought
//! of still reads.
//!
//! A large part of the table is a *private-use* code point rather than the
//! standard Unicode look-alike: `\[WarningSign]` is U+F725, not U+26A0,
//! `\[Equal]` is U+F431, `\[Rule]` is U+F522, `\[Cross]` is U+F4A0, and the
//! whole script alphabet lives at U+F770… / U+F6B2… . Strings have to compare
//! and measure equal to Wolfram's, so that is what is stored; only Wolfram's
//! own fonts draw those code points, so text that gets *drawn* runs through
//! [`crate::syntax::substitute_private_use_glyphs`] first.
//!
//! Names Wolfram has no character for — `\[Tab]`, `\[Male]`, `\[Female]`,
//! `\[Registered]`, `\[CarriageReturn]`, `\[RawNewline]` — are absent here
//! on purpose: the reader warns `Syntax::sntufn` and leaves the escape in the
//! string as written.

