/// Canonical isotope name Woxi's entity uses: the parent element's standard
/// name followed by the mass number, e.g. `"Carbon12"`.
fn canonical_name(iso: &Isotope) -> String {
  format!("{}{}", iso.element_name, iso.mass_number)
}

fn isotope_entity(iso: &'static Isotope) -> Expr {
  call(
    "Entity",
    vec![
      Expr::String("Isotope".to_string()),
      Expr::String(canonical_name(iso)),
    ],
  )
}

fn find_isotope_by_name(name: &str) -> Option<&'static Isotope> {
  ISOTOPES.iter().find(|iso| canonical_name(iso) == name)
}

/// Resolves an isotope specifier: `Entity["Isotope", name]`, a bare
/// canonical name string, or `{element, massNumber}`.
fn find_isotope(identifier: &Expr) -> Option<&'static Isotope> {
  match identifier {
    Expr::FunctionCall { name, args }
      if name == "Entity" && args.len() == 2 =>
    {
      match (&args[0], &args[1]) {
        (Expr::String(kind), Expr::String(iso_name)) if kind == "Isotope" => {
          find_isotope_by_name(iso_name)
        }
        _ => None,
      }
    }
    Expr::String(s) => find_isotope_by_name(s),
    Expr::List(items) if items.len() == 2 => {
      let (atomic_number, _) = resolve_element(&items[0])?;
      let mass_number = match &items[1] {
        Expr::Integer(n) => *n,
        _ => return None,
      };
      ISOTOPES.iter().find(|iso| {
        iso.atomic_number == atomic_number && iso.mass_number == mass_number
      })
    }
    _ => None,
  }
}

fn isotopes_for_element(atomic_number: i128) -> Vec<&'static Isotope> {
  let mut isos: Vec<&'static Isotope> = ISOTOPES
    .iter()
    .filter(|iso| iso.atomic_number == atomic_number)
    .collect();
  isos.sort_by_key(|iso| iso.mass_number);
  isos
}

/// Total nuclear binding energy in MeV, from the mass-excess formula
/// `BE = (Z·m(¹H) + N·m(n) − M(A,Z))·c²`. Electron binding-energy
/// differences between the `Z` free ¹H atoms and the neutral isotope are of
/// order eV and are dropped at this MeV-scale precision.
fn binding_energy_mev(iso: &Isotope) -> f64 {
  let hydrogen1_mass = ISOTOPES
    .iter()
    .find(|h| h.atomic_number == 1 && h.mass_number == 1)
    .map(|h| h.atomic_mass)
    .expect("hydrogen-1 is always in the bundled isotope table");
  let z = iso.atomic_number as f64;
  let n = (iso.mass_number - iso.atomic_number) as f64;
  (z * hydrogen1_mass + n * NEUTRON_MASS_U - iso.atomic_mass) * U_TO_MEV
}

// Alphabetical list of property names IsotopeData can be queried with.
static SUPPORTED_PROPERTIES: &[&str] = &[
  "AtomicMass",
  "AtomicNumber",
  "BindingEnergy",
  "IsotopeAbundance",
  "MassNumber",
  "NeutronNumber",
  "StandardName",
];

fn get_isotope_property(iso: &Isotope, property: &str) -> Expr {
  match property {
    "MassNumber" => Expr::Integer(iso.mass_number),
    "AtomicNumber" => Expr::Integer(iso.atomic_number),
    "NeutronNumber" => Expr::Integer(iso.mass_number - iso.atomic_number),
    "AtomicMass" => crate::functions::element_data::make_quantity(
      Expr::Real(iso.atomic_mass),
      "Daltons",
    ),
    "IsotopeAbundance" => match iso.abundance {
      Some(a) => Expr::Real(a),
      None => missing_not_available(),
    },
    "BindingEnergy" => crate::functions::element_data::make_quantity(
      Expr::Real(binding_energy_mev(iso)),
      "Megaelectronvolts",
    ),
    "StandardName" => Expr::String(canonical_name(iso)),
    _ => missing_not_available(),
  }
}

/// All bundled isotopes as `Entity["Isotope", name]`, sorted by (atomic
/// number, mass number) — the "All" / no-argument answer.
fn all_isotope_entities() -> Vec<Expr> {
  let mut isos: Vec<&'static Isotope> = ISOTOPES.iter().collect();
  isos.sort_by_key(|iso| (iso.atomic_number, iso.mass_number));
  isos.into_iter().map(isotope_entity).collect()
}

pub fn isotope_data_ast(args: &[Expr]) -> Result<Expr, InterpreterError> {
  match args.len() {
    0 => Ok(Expr::List(all_isotope_entities().into())),
    1 => match &args[0] {
      Expr::String(s) if s == "Properties" => {
        let props: Vec<Expr> = SUPPORTED_PROPERTIES
          .iter()
          .map(|p| Expr::String(p.to_string()))
          .collect();
        Ok(Expr::List(props.into()))
      }
      Expr::Identifier(s) if s == "All" => {
        Ok(Expr::List(all_isotope_entities().into()))
      }
      identifier => match resolve_element(identifier) {
        Some((atomic_number, _)) => {
          let entities: Vec<Expr> = isotopes_for_element(atomic_number)
            .into_iter()
            .map(isotope_entity)
            .collect();
          Ok(Expr::List(entities.into()))
        }
        None => match find_isotope(identifier) {
          Some(iso) => Ok(isotope_entity(iso)),
          None => Ok(unevaluated("IsotopeData", args)),
        },
      },
    },
    2 => {
      // `IsotopeData[All, "Preload"]` is a caching hint with no return
      // value in a script context.
      if matches!(&args[0], Expr::Identifier(s) if s == "All")
        && matches!(&args[1], Expr::String(p) if p == "Preload")
      {
        return Ok(null_expr());
      }
      let Expr::String(property) = &args[1] else {
        return Ok(unevaluated("IsotopeData", args));
      };
      match find_isotope(&args[0]) {
        Some(iso) => Ok(get_isotope_property(iso, property)),
        None => Ok(unevaluated("IsotopeData", args)),
      }
    }
    _ => Ok(unevaluated("IsotopeData", args)),
  }
}

/// The bundled isotopes of one element as `Entity["Isotope", name]`,
/// sorted by mass number — used by `ElementData[…, "StableIsotopes"]`,
/// which shares the same NIST-sourced table.
///
/// "Stable" here means NIST reports a measured natural abundance for the
/// isotope, which is a coarser cut than true nuclear stability: long-lived
/// primordial radionuclides that still occur naturally (e.g. potassium-40,
/// thorium-232) are included, matching how these elements are
/// conventionally described in chemistry references.
pub(crate) fn stable_isotope_entities(atomic_number: i128) -> Vec<Expr> {
  isotopes_for_element(atomic_number)
    .into_iter()
    .filter(|iso| iso.abundance.is_some())
    .map(isotope_entity)
    .collect()
}
